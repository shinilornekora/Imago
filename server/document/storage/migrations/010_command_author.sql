-- 010_command_author.sql — имя автора команды у транзакции агента (круг 30).
--
-- Транзакцию агента пишет Orchestrator от имени «Агент» (`author`); кто ДАЛ команду, журнал
-- не знал — подпись «Агент · Аня» у опоздавших держалась на памяти вкладки (присутствие), и
-- браузер, ни разу не видевший Аню в сети, писал просто «Агент». Теперь имя автора команды
-- лежит в записи: `command_author` (≤ 200 символов, чистый текст) — его отдают Committed,
-- сокет и `/history`.
--
-- Смешанные версии (SPEC §9.11): ADD COLUMN без умолчания — правка каталога без перезаписи
-- таблицы (эксклюзивный замок на миг; раннер ждёт его не дольше lock_timeout и повторяет).
-- Экземпляр прежней версии колонку не знает: читает журнал явным списком колонок, его INSERT
-- оставляет её NULL — запись выглядит как прежде («Агент» без имени). Экземпляр этой версии
-- до миграции (каталог без 010) колонку не пишет и не читает — проверяет её наличие после
-- миграций. Дозаполнять нечего: имени у старых записей нет нигде.

ALTER TABLE operations ADD COLUMN IF NOT EXISTS command_author text;
