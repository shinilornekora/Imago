-- 013_create_hash.sql — отпечаток тела создания проекта рядом с create_id (круг 35, L1).
--
-- Повтор POST /api/projects с тем же create_id и ДРУГИМ телом (другое имя, вид, документ) прежде
-- молча отдавал старый проект — клиент думал, что создал то, что просил. Теперь вместе с
-- create_id пишется sha256 тела без create_id (`create_hash`); повтор с другим отпечатком — 409
-- `create_id_conflict`. Строки без отпечатка (созданы до 013 или экземпляром прежней версии) —
-- сверка только по виду проекта (имя могли переименовать).
--
-- Смешанные версии (SPEC §9.11): ADD COLUMN без умолчания — правка каталога без перезаписи
-- таблицы; прежний экземпляр колонку не знает и оставляет NULL.

ALTER TABLE projects ADD COLUMN IF NOT EXISTS create_hash text;
