-- 011_undo_part.sql — часть большой правки у записи журнала (круг 32).
--
-- Правка больше предела транзакции (5000 операций или 3,5 МБ) — отмена удаления большой доски,
-- импорт большого файла — уходит несколькими транзакциями подряд (круг 31, K1). Каждая несёт
-- `undo_part: {i, n}` (номер с 0 и число частей); у отмены и повтора — ещё общий `undo_of`/
-- `redo_of`. Прежде сервер `undo_part` не хранил, и чужая «История» сводила части по подписи
-- («… · часть 2 из 3»). Теперь он лежит в записи — его отдают Committed, сокет и `/history`.
--
-- Смешанные версии (SPEC §9.11) — как 010: ADD COLUMN без умолчания — правка каталога без
-- перезаписи таблицы. Экземпляр прежней версии колонку не знает: читает журнал явным списком
-- колонок, его INSERT оставляет NULL (части такой правки в чужой «Истории» — отдельными строками).
-- Экземпляр этой версии до миграции колонку не пишет и не читает — проверяет её наличие после
-- миграций. Дозаполнять нечего: у старых записей частей не сохранилось.

ALTER TABLE operations ADD COLUMN IF NOT EXISTS undo_part jsonb;
