-- 012_create_id.sql — идемпотентное создание проекта (круг 33, L1).
--
-- Оболочка создаёт проект «спасением» (проекта не стало после восстановления базы) или импортом
-- в новый проект; ответ на POST /api/projects мог потеряться (обрыв, перезагрузка вкладки) — и
-- повтор создавал второй такой же проект. Теперь запрос несёт `create_id` (8–64 символа
-- [A-Za-z0-9_-], заводится клиентом один раз на задание): повтор с тем же create_id — 200 с тем
-- же проектом, без второго создания.
--
-- Смешанные версии (SPEC §9.11): ADD COLUMN без умолчания — правка каталога без перезаписи
-- таблицы; уникальность — частичным индексом только по непустым значениям: экземпляр прежней
-- версии колонку не знает, его INSERT оставляет NULL, и таких строк сколько угодно. Таблица
-- проектов маленькая (строка на проект) — обычный CREATE INDEX в транзакции миграции держит
-- запись проектов миллисекунды (раннер ждёт замка не дольше lock_timeout и повторяет).

ALTER TABLE projects ADD COLUMN IF NOT EXISTS create_id text;
CREATE UNIQUE INDEX IF NOT EXISTS projects_create_id ON projects (create_id) WHERE create_id IS NOT NULL;
