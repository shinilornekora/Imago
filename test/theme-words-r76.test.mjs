/**
 * Круг 76 (SPEC §15.13): без модели — «сделай эти экраны тёмными», «все экраны оплаты сделай тёмными»,
 * «экраны Итог и Профиль в розовом акценте», «перекрась экраны оплаты» — оформление; правки слоёв
 * на экране («сделай карточку на экране тёмной», «перекрась кнопку на экране») и создание — как были.
 */
import test from 'node:test';
import assert from 'node:assert/strict';
import { classifyUtterance } from '../src/brain.js';

const THEME = [
  'сделай все экраны, кроме оплаты, тёмными', 'все экраны оплаты сделай тёмными', 'экраны Итог и Профиль в розовом акценте',
  'сделай эти экраны тёмными', 'сделай этот экран тёмным', 'сделай документ светлым', 'перекрась экраны оплаты в зелёный',
  'сделай экран Итог с розовым акцентом', 'оформи экран профиля в светлых тонах',
  'сделай весь документ тёмным', 'сделай тёмными все экраны', 'сделай экраны потемнее', 'затемни экраны',
  'осветли все экраны', 'покрась экраны оплаты в тёмный', 'сделай экраны «Итог» и «Профиль» тёмными',
];
const NOT = [
  ['удали все экраны, кроме оплаты', 'edit'], ['перекрась кнопку на экране оплаты', 'edit'], ['сделай кнопку на экране светлее', 'edit'],
  ['собери экран входа в тёмных тонах', 'create'], ['собери экран входа с розовым акцентом', 'create'],
];
// критик круга 76: слои на экране, свойство экрана («с тёмным фоном»), «на экране …» — не тема
const NOT_THEME = [
  'сделай экран заказа: заголовок тёмный', 'сделай экран заказа, заголовок тёмный', 'сделай экран заказа, у кнопки текст тёмный',
  'сделай экран заказа шире и шапку светлее', 'сделай экраны шире и подложку светлее', 'сделай экран выше, фон светлый оставь',
  'сделай экран входа и кнопку на нём светлой', 'сделай экран, на котором светлый текст', 'сделай экран: тёмная карточка с ценой',
  'сделай экран заказа с тёмной шапкой', 'сделай экран оплаты с тёмным фоном', 'сделай экран со светлой кнопкой',
  'на экране заказа заголовок сделай светлым', 'экран заказа: кнопку сделай тёмной', 'на экране входа кнопку сделай светлее',
  'экраны с карточками сделай светлыми', 'удали кнопки на экране с зелёным акцентом', 'перемести кнопку на экране в синем акценте',
  'на экране заказа кнопка в синем акценте', 'экран входа с кнопкой в синем акценте', 'сделай экранную кнопку светлой',
  'сделай экранированные тёмные блоки', 'перекрась экран заказа кнопку', 'сделай макет кнопки тёмным',
];

test('круг76: экраны целиком — оформление без модели', () => {
  for (const u of THEME) assert.equal(classifyUtterance(u).intent, 'theme', u);
});

test('круг76: правки слоёв на экране и создание экрана — не оформление', () => {
  for (const [u, want] of NOT) assert.equal(classifyUtterance(u).intent, want, u);
  assert.notEqual(classifyUtterance('сделай карточку на этом экране тёмной').intent, 'theme');
});

test('круг76, критики: слои на экране и свойства экрана — не оформление', () => {
  for (const u of NOT_THEME) assert.notEqual(classifyUtterance(u).intent, 'theme', u);
});
