/**
 * Круг 76 (SPEC §15.13): без модели — «сделай эти экраны тёмными», «все экраны оплаты сделай тёмными»,
 * «экраны Итог и Профиль в розовом акценте», «перекрась экраны оплаты» — оформление; правки слоёв
 * на экране («сделай карточку на экране тёмной», «перекрась кнопку на экране») и создание — как были.
 */
import test from 'node:test';
import assert from 'node:assert/strict';
import { classifyUtterance } from '../src/brain.js';

const THEME = [
  'сделай все экраны, кроме оплаты, тёмными', 'все экраны оплаты сделай тёмными', 'экраны Итог и Профиль в розовом акценте',
  'сделай эти экраны тёмными', 'сделай этот экран тёмным', 'сделай документ светлым', 'перекрась экраны оплаты в зелёный',
  'сделай экран Итог с розовым акцентом', 'оформи экран профиля в светлых тонах',
];
const NOT = [
  ['удали все экраны, кроме оплаты', 'edit'], ['перекрась кнопку на экране оплаты', 'edit'], ['сделай кнопку на экране светлее', 'edit'],
  ['собери экран входа в тёмных тонах', 'create'], ['собери экран входа с розовым акцентом', 'create'],
];

test('круг76: экраны целиком — оформление без модели', () => {
  for (const u of THEME) assert.equal(classifyUtterance(u).intent, 'theme', u);
});

test('круг76: правки слоёв на экране и создание экрана — не оформление', () => {
  for (const [u, want] of NOT) assert.equal(classifyUtterance(u).intent, want, u);
  assert.notEqual(classifyUtterance('сделай карточку на этом экране тёмной').intent, 'theme');
});
